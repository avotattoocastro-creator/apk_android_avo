#!/usr/bin/env python3
"""Generates src/ui_assets.h: anti-aliased 4-bit fonts and icons stored in flash.

Fonts : Barlow Condensed (SIL OFL 1.1) — github.com/google/fonts ofl/barlowcondensed
Icons : Font Awesome Free 7 (fonts SIL OFL 1.1, icons CC BY 4.0) — github.com/FortAwesome/Font-Awesome

Usage: gen_ui_assets.py BARLOW_DIR FONTAWESOME_OTF_DIR OUT_HEADER

Everything is `const` data (flash, no RAM). Alpha is 4 bits per pixel, two pixels per byte,
rows padded to whole bytes.
"""
import sys
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

barlow, fa_dir, out = Path(sys.argv[1]), Path(sys.argv[2]), Path(sys.argv[3])

LATIN1_EXTRA = "°·¡¿ÁÉÍÓÚÜÑáéíóúüñ"
TEXT = "".join(chr(c) for c in range(0x20, 0x7F)) + LATIN1_EXTRA
DIGITS = " 0123456789%-.:/"

FONTS = [
    # name, file, pixel size, charset
    ("F_TITLE", "BarlowCondensed-Bold.ttf", 31, TEXT),
    ("F_STATE", "BarlowCondensed-SemiBold.ttf", 25, TEXT),
    ("F_SMALL", "BarlowCondensed-SemiBold.ttf", 21, TEXT),
    ("F_TINY", "BarlowCondensed-SemiBold.ttf", 17, TEXT),
    ("F_BIG", "BarlowCondensed-Bold.ttf", 54, DIGITS),
    ("F_HUGE", "BarlowCondensed-Bold.ttf", 96, DIGITS),
]

SOLID = "Font Awesome 7 Free-Solid-900.otf"
BRANDS = "Font Awesome 7 Brands-Regular-400.otf"
ICONS = [
    # name, font, codepoint, target height (px)
    ("I_BLUETOOTH", BRANDS, 0xF294, 40),
    ("I_VEST", SOLID, 0xE085, 40),
    ("I_BROADCAST", SOLID, 0xF519, 34),
    ("I_HORSE", SOLID, 0xF6F0, 36),
    ("I_SATELLITE", SOLID, 0xF7BF, 40),
    ("I_SDCARD", SOLID, 0xF7C2, 40),
    ("I_PHONE", SOLID, 0xF3CF, 30),
    ("I_NODES", SOLID, 0xE4E2, 28),
    ("I_CROSSHAIRS", SOLID, 0xF05B, 28),
    ("I_BOLT", SOLID, 0xF0E7, 40),
    ("I_CHECK", SOLID, 0xF00C, 17),
    ("I_XMARK", SOLID, 0xF00D, 17),
]


def pack4(img):
    w, h = img.size
    px = img.load()
    out = bytearray()
    for y in range(h):
        row = [(px[x, y] * 15 + 127) // 255 for x in range(w)]
        if w % 2:
            row.append(0)
        for i in range(0, len(row), 2):
            out.append((row[i] << 4) | row[i + 1])
    return out


def c_array(name, data):
    lines = []
    for i in range(0, len(data), 24):
        lines.append("  " + ",".join(f"0x{b:02X}" for b in data[i:i + 24]) + ",")
    return f"static const uint8_t {name}[{max(len(data), 1)}] = {{\n" + "\n".join(lines or ["  0"]) + "\n};\n"


parts = ["// GENERATED by tools/gen_ui_assets.py — do not edit by hand.",
         "// Barlow Condensed: SIL OFL 1.1. Font Awesome Free 7: fonts SIL OFL 1.1, icons CC BY 4.0.",
         "#pragma once", "#include <stdint.h>", '#include "ui_fb.h"', "namespace ui_assets {", ""]
total = 0
summary = []

for name, file, size, charset in FONTS:
    font = ImageFont.truetype(str(barlow / file), size)
    ascent, descent = font.getmetrics()
    bitmap = bytearray()
    glyphs = {}
    for ch in sorted(set(charset), key=ord):
        code = ord(ch)
        adv = int(round(font.getlength(ch)))
        box = font.getbbox(ch, anchor="ls")
        w, h = box[2] - box[0], box[3] - box[1]
        if w <= 0 or h <= 0:
            glyphs[code] = (len(bitmap), 0, 0, 0, 0, adv)
            continue
        img = Image.new("L", (w, h), 0)
        ImageDraw.Draw(img).text((-box[0], -box[1]), ch, font=font, fill=255, anchor="ls")
        glyphs[code] = (len(bitmap), w, h, box[0], box[1], adv)
        bitmap += pack4(img)
    first, last = 0x20, max(glyphs)
    table = []
    for code in range(first, last + 1):
        g = glyphs.get(code)
        table.append("{%d,%d,%d,%d,%d,%d,0}" % g if g else "{0,0,0,0,0,0,0}")
    parts.append(c_array(f"{name}_bits", bitmap))
    parts.append(f"static const UiGlyph {name}_glyphs[{len(table)}] = {{\n  " +
                 ",\n  ".join(", ".join(table[i:i + 8]) for i in range(0, len(table), 8)) + "\n};")
    parts.append(f"static const UiFont {name} = {{{name}_bits, {name}_glyphs, {first}, {last}, {ascent}, {descent}}};\n")
    total += len(bitmap) + len(table) * 8
    summary.append(f"{name}: {size}px, {len(glyphs)} glifos, {len(bitmap)} B")

for name, file, code, target in ICONS:
    probe = ImageFont.truetype(str(fa_dir / file), 100)
    box = probe.getbbox(chr(code))
    gh = box[3] - box[1]
    font = ImageFont.truetype(str(fa_dir / file), max(4, round(100 * target / gh)))
    box = font.getbbox(chr(code))
    w, h = box[2] - box[0], box[3] - box[1]
    img = Image.new("L", (w, h), 0)
    ImageDraw.Draw(img).text((-box[0], -box[1]), chr(code), font=font, fill=255)
    data = pack4(img)
    parts.append(c_array(f"{name}_bits", data))
    parts.append(f"static const UiIcon {name} = {{{name}_bits, {w}, {h}}};\n")
    total += len(data)
    summary.append(f"{name}: {w}x{h}")

parts.append("}  // namespace ui_assets")
parts.append(f"// Total flash data: {total} bytes")
out.write_text("\n".join(parts) + "\n")
print("\n".join(summary))
print(f"Total flash data: {total} bytes -> {out}")
